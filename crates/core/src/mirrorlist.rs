use chrono::{DateTime, Utc};

use crate::Mirror;

/// Information embedded in the mirrorlist header comment.
pub struct HeaderInfo<'a> {
    pub when: DateTime<Utc>,
    pub filters: &'a str,
    pub sort: &'a str,
    pub source: &'a str,
}

/// Make a string safe to embed in a single comment line.
pub fn sanitize_comment(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_control() { ' ' } else { c })
        .collect()
}

/// The `Server = ` line for a mirror.
pub fn server_line(m: &Mirror) -> String {
    format!("Server = {}$repo/os/$arch", m.base_url())
}

/// Render a reflector-style mirrorlist.
pub fn generate(mirrors: &[&Mirror], info: &HeaderInfo<'_>) -> String {
    let mut s = String::new();
    s.push_str("##\n## Arch Linux repository mirrorlist\n");
    s.push_str(&format!(
        "## Generated by mirrorscope {}\n",
        env!("CARGO_PKG_VERSION")
    ));
    s.push_str(&format!(
        "## When: {}\n",
        info.when.format("%Y-%m-%d %H:%M:%S UTC")
    ));
    s.push_str(&format!("## With: {}\n", sanitize_comment(info.filters)));
    s.push_str(&format!("## Sort: {}\n", sanitize_comment(info.sort)));
    s.push_str(&format!(
        "## From: {}\n##\n\n",
        sanitize_comment(info.source)
    ));
    for m in mirrors {
        s.push_str(&server_line(m));
        s.push('\n');
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::StatusDocument;

    #[test]
    fn generates_header_and_servers() {
        let doc = StatusDocument::parse(include_str!("../tests/fixtures/status.json")).unwrap();
        let refs: Vec<&Mirror> = doc.urls.iter().take(2).collect();
        let info = HeaderInfo {
            when: "2026-11-12T10:00:00Z".parse().unwrap(),
            filters: "protocol=https",
            sort: "score",
            source: "https://archlinux.org/mirrors/status/json/",
        };
        let out = generate(&refs, &info);
        assert!(out.contains("## When: 2026-11-12 10:00:00 UTC"));
        assert!(out.contains("## With: protocol=https"));
        assert!(out.contains("Server = https://de1.example.org/archlinux/$repo/os/$arch\n"));
        assert!(out.contains("Server = http://de2.example.org/archlinux/$repo/os/$arch\n"));
        assert_eq!(out.lines().filter(|l| l.starts_with("Server")).count(), 2);
        // every non-empty line is a comment or a Server line
        for l in out.lines() {
            assert!(l.is_empty() || l.starts_with('#') || l.starts_with("Server = "));
        }
    }

    #[test]
    fn header_cannot_be_injected_via_filters() {
        let doc = StatusDocument::parse(include_str!("../tests/fixtures/status.json")).unwrap();
        let refs: Vec<&Mirror> = doc.urls.iter().take(1).collect();
        let info = HeaderInfo {
            when: Utc::now(),
            filters: "x\nServer = http://evil/$repo/os/$arch",
            sort: "s\r\nInclude = /etc/passwd",
            source: "src",
        };
        let out = generate(&refs, &info);
        for l in out.lines() {
            assert!(
                l.is_empty()
                    || l.starts_with('#')
                    || l == "Server = https://de1.example.org/archlinux/$repo/os/$arch",
                "unexpected line: {l}"
            );
        }
    }
}
